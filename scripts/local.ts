import { loadEnvConfig } from "@next/env";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";
import { spawn, type ChildProcess } from "node:child_process";
import { createServer, type Server } from "node:net";
import { appendFile, mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import type { Database, SqlConnection } from "../src/server/database";
import { initializeLocal } from "./local-setup";

const root = process.cwd();
const localDir = resolve(root, ".local");
const databaseUrl = "postgresql://postgres:postgres@127.0.0.1:55432/postgres";
let mutex: Server | undefined;
let engine: PGlite | undefined;
let socket: PGLiteSocketServer | undefined;
let web: ChildProcess | undefined;
let stopping = false;

async function stop(code = 0) {
  if (stopping) return;
  stopping = true;
  if (web?.pid && web.exitCode === null && web.signalCode === null) {
    const exited = new Promise<void>((resolve) =>
      web!.once("exit", () => resolve()),
    );
    if (process.platform === "win32" && web.pid) {
      // Next dev has a child worker; stop only this launcher's process tree.
      const killer = spawn("taskkill", ["/PID", String(web.pid), "/T", "/F"], {
        stdio: "ignore",
        windowsHide: true,
      });
      killer.once("error", () => web?.kill("SIGTERM"));
    } else web.kill("SIGTERM");
    await exited;
  }
  await socket?.stop();
  await engine?.close();
  await new Promise<void>((resolve) =>
    mutex?.listening ? mutex.close(() => resolve()) : resolve(),
  );
  process.exitCode = code;
}

async function main() {
  if (process.env.NODE_ENV === "production")
    throw new Error("Use this launcher only for local development.");
  if (process.argv.slice(2).some((arg) => arg !== "--database-only"))
    throw new Error("Supported option: --database-only");
  // Claim a fixed loopback port before opening the files. The OS releases this
  // guard on process exit, preventing two launchers from sharing a PGlite directory.
  mutex = createServer((connection) => connection.end());
  await new Promise<void>((resolve, reject) => {
    mutex!.once("error", reject);
    mutex!.listen(55433, "127.0.0.1", resolve);
  }).catch(() => {
    throw new Error(
      "Another local launcher is running, or local guard port 55433 is occupied. Stop it before restarting.",
    );
  });
  try {
    await writeFile(
      resolve(root, ".env.local"),
      "# Local development. Generated by npm run local.\nDATABASE_URL=" +
        databaseUrl +
        "\nAPP_ORIGIN=http://localhost:3000\nNEXT_TELEMETRY_DISABLED=1\n",
      { flag: "wx", mode: 0o600 },
    );
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
  }
  loadEnvConfig(root, true);
  if (
    process.env.DATABASE_URL !== databaseUrl ||
    process.env.APP_ORIGIN !== "http://localhost:3000"
  ) {
    throw new Error(
      "Local mode needs DATABASE_URL=" +
        databaseUrl +
        " and APP_ORIGIN=http://localhost:3000. Your existing environment was preserved; update it or use the configured database with npm run dev.",
    );
  }
  await mkdir(localDir, { recursive: true });
  engine = await PGlite.create(resolve(localDir, "postgres"));
  const adapt = (connection: Pick<PGlite, "query">): SqlConnection => ({
    async query<T>(sql: string, values?: unknown[]) {
      const result = await connection.query<T>(sql, values);
      return { rows: result.rows };
    },
  });
  const db: Database = {
    ...adapt(engine),
    transaction: (work) =>
      engine!.transaction((tx) => work(adapt(tx as unknown as PGlite))),
  };
  const credentials = await initializeLocal(db);
  if (credentials.length) {
    await appendFile(
      resolve(localDir, "credentials.txt"),
      "Local development accounts — http://localhost:3000/en/login\n" +
        credentials
          .map(
            (account) =>
              account.username +
              " (" +
              account.role +
              ")\nPassword: " +
              account.password,
          )
          .join("\n\n") +
        "\n\nKeep this file private. Accounts and data are preserved on restart.\n\n",
      { mode: 0o600 },
    );
  }
  socket = new PGLiteSocketServer({
    db: engine,
    host: "127.0.0.1",
    port: 55432,
    maxConnections: 10,
  });
  await socket.start();
  console.log("Local database ready. Data: " + resolve(localDir, "postgres"));
  console.log("Staff login details: " + resolve(localDir, "credentials.txt"));
  console.log("Press Ctrl+C to stop. Your data will remain on disk.");
  if (process.argv.includes("--database-only")) return;
  web = spawn(
    process.execPath,
    [
      resolve(root, "node_modules/next/dist/bin/next"),
      "dev",
      "--hostname",
      "127.0.0.1",
      "--port",
      "3000",
    ],
    {
      cwd: root,
      stdio: "inherit",
      env: { ...process.env, NEXT_TELEMETRY_DISABLED: "1" },
    },
  );
  web.once("error", (error) => {
    console.error(error.message);
    void stop(1);
  });
  web.once("exit", (code) => {
    if (!stopping) void stop(code ?? 1);
  });
}

process.on("SIGINT", () => void stop());
process.on("SIGTERM", () => void stop());
main().catch(async (error) => {
  console.error(
    error instanceof Error ? error.message : "Local startup failed.",
  );
  await stop(1);
});
